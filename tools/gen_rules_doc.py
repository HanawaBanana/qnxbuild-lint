#!/usr/bin/env python3
"""Generate docs/rules.md from the rule and attribute tables.

The tables in ``qnxbuild_lint`` are the single source of truth; this script
keeps the published documentation from drifting away from them.

Usage:
    python3 tools/gen_rules_doc.py           # write docs/rules.md
    python3 tools/gen_rules_doc.py --check   # exit 1 if docs/rules.md is stale
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from qnxbuild_lint.attributes import (  # noqa: E402
    BOOLEAN_ATTRIBUTES,
    TYPE_VALUES,
    VALUE_ATTRIBUTES,
)
from qnxbuild_lint.cli import RULES  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "rules.md"


def render() -> str:
    lines = [
        "# Rules",
        "",
        "Generated by `tools/gen_rules_doc.py` from the tables in `qnxbuild_lint/`.",
        "Do not edit by hand; run the script instead (CI fails when it is stale).",
        "",
        "Every rule is grounded in the QNX SDP 8.0 `mkifs` reference",
        "(attribute list, inline-file and script-scope sections) or in the QNX",
        "recursive Makefile model (`LIST=` plus `include recurse.mk`).",
        "",
        "## Diagnostics",
        "",
        "| Rule | Severity | Meaning |",
        "|---|---|---|",
    ]
    for rule, text in sorted(RULES.items()):
        severity = "warning" if rule in {"ATTR_DUPLICATE", "FILE_DUPLICATE_TARGET"} else "error"
        lines.append(f"| `{rule}` | {severity} | {text} |")
    lines += [
        "",
        "## Attributes accepted by the parser",
        "",
        "Boolean attributes (written `+name` / `-name`, `?` makes them conditional):",
        "",
        ", ".join(f"`{name}`" for name in sorted(BOOLEAN_ATTRIBUTES)),
        "",
        "Value attributes (written `name=value`):",
        "",
        ", ".join(f"`{name}`" for name in sorted(VALUE_ATTRIBUTES)),
        "",
        f"`type=` values: {', '.join(f'`{v}`' for v in sorted(TYPE_VALUES))}.",
        "",
        "Anything else in an attribute group is reported as `ATTR_UNKNOWN`; a",
        "bare `[name]` header whose name is unknown is reported as",
        "`SECTION_UNKNOWN` (typical of buildfiles borrowed from another build",
        "system, e.g. a Meson-style `[block]` section).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/rules.md is stale; run tools/gen_rules_doc.py", file=sys.stderr)
            return 1
        print("docs/rules.md is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
